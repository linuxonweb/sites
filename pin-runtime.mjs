// Explicitly pin a reviewed snapshot; this never runs during ordinary builds.
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const [input, parentCommit] = process.argv.slice(2);
if (!input || !/^[a-f0-9]{40}$/.test(parentCommit || '')) throw new Error('usage: node pin-runtime.mjs SNAPSHOT_DIRECTORY FULL_PARENT_COMMIT');
const root = dirname(fileURLToPath(import.meta.url)), snapshot = resolve(input);
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const manifestBytes = await readFile(resolve(snapshot,'generated/asset-manifest.mjs'));
const text = manifestBytes.toString(), prefix = '// Generated by stage-assets.mjs. Do not edit.\nexport default ';
if (!text.startsWith(prefix) || !text.endsWith(';\n')) throw new Error('unexpected staged manifest');
const original = JSON.parse(text.slice(prefix.length,-2));
const reportBytes = await readFile(resolve(snapshot,'generated/build-report.json')), report = JSON.parse(reportBytes);
if (report.routes !== 58 || report.stagedFiles !== 55 || report.stagedBytes !== 151597037 || report.sourceFiles.length !== 50) throw new Error('snapshot differs from reviewed release');
const parts = new Map(), routes = {};
for (const [path,entry] of Object.entries(original)) {
  if (!/^\/(linux|desktop|upstream)\//.test(path) || path.includes('/tests/') || path.includes('..')) throw new Error('unapproved route');
  const logicalHash = createHash('sha256'), mapped = []; let size = 0;
  for (const part of entry.parts) {
    if (!part.path.startsWith('/') || part.path.includes('..') || !Number.isSafeInteger(part.size) || part.size <= 0 || part.size > 20*1024*1024) throw new Error('invalid part');
    const bytes = await readFile(resolve(snapshot,'public','.'+part.path)), sha256 = hash(bytes);
    if (bytes.length !== part.size) throw new Error('part size mismatch');
    const pin = {source:part.path,path:'/_runtime_assets/'+sha256+'.bin',size:bytes.length,sha256};
    if (parts.has(part.path) && JSON.stringify(parts.get(part.path)) !== JSON.stringify(pin)) throw new Error('part changed during pin');
    parts.set(part.path,pin); mapped.push({path:pin.path,size:pin.size}); logicalHash.update(bytes); size += bytes.length;
  }
  if (size !== entry.size || logicalHash.digest('hex') !== entry.sha256) throw new Error('logical hash mismatch: '+path);
  routes[path] = {...entry,parts:mapped};
}
if (Object.keys(routes).length !== report.routes || parts.size !== report.stagedFiles || [...parts.values()].reduce((n,p)=>n+p.size,0) !== report.stagedBytes) throw new Error('snapshot counts mismatch');
for (const source of report.sourceFiles) {
  const entry=original[source.path];
  if (!entry || entry.size !== source.size || entry.sha256 !== source.sha256) throw new Error('report/manifest mismatch');
}
const module = '// Pinned runtime routes. Update only with pin-runtime.mjs.\nexport default '+JSON.stringify(routes,null,2)+';\n';
const lock = {schema:1,parentCommit,stagedBytes:report.stagedBytes,stagedFiles:parts.size,routes:report.routes,
  runtimeManifestSHA256:hash(module),inputManifestSHA256:hash(manifestBytes),inputBuildReportSHA256:hash(reportBytes),
  parts:[...parts.values()].sort((a,b)=>a.source.localeCompare(b.source))};
await writeFile(resolve(root,'runtime-assets.mjs'),module);
await writeFile(resolve(root,'runtime-lock.json'),JSON.stringify(lock,null,2)+'\n');
console.log(JSON.stringify({parentCommit,routes:lock.routes,parts:lock.stagedFiles,stagedBytes:lock.stagedBytes,runtimeManifestSHA256:lock.runtimeManifestSHA256}));
