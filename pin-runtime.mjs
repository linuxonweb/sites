// Explicitly pin a reviewed snapshot; ordinary builds never repin inputs.
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { approvedRoutes, runtimeSources, runtimeAliases } from './release-runtime.mjs';
const root=dirname(fileURLToPath(import.meta.url));
const hash=bytes=>createHash('sha256').update(bytes).digest('hex');
const same=(a,b)=>JSON.stringify(a)===JSON.stringify(b);
const sha=value=>/^[a-f0-9]{64}$/.test(value||'');
const positive=value=>Number.isSafeInteger(value)&&value>0;

export async function pinRuntime(input,parentCommit,provenancePath,output=root) {
  if(!input||!/^[a-f0-9]{40}$/.test(parentCommit||'')||!provenancePath)throw new Error('usage: node pin-runtime.mjs SNAPSHOT_DIRECTORY FULL_PARENT_COMMIT REVIEWED_RELEASE_PROVENANCE_JSON');
  const snapshot=resolve(input),provenanceBytes=await readFile(resolve(provenancePath)),provenance=JSON.parse(provenanceBytes);
  if(provenance.schema!==1||provenance.parentCommit!==parentCommit||!same(provenance.approvedRoutes,approvedRoutes)||
    !same(provenance.aliases,runtimeAliases)||!sha(provenance.auditSHA256)||
    provenance.helperSHA256!==hash(await readFile(resolve(root,'release-runtime.mjs'))))throw new Error('unapproved release provenance');
  const manifestBytes=await readFile(resolve(snapshot,'generated/asset-manifest.mjs'));
  const text=manifestBytes.toString(),prefix='// Generated by stage-assets.mjs. Do not edit.\nexport default ';
  if(!text.startsWith(prefix)||!text.endsWith(';\n'))throw new Error('unexpected staged manifest');
  const original=JSON.parse(text.slice(prefix.length,-2));
  const reportBytes=await readFile(resolve(snapshot,'generated/build-report.json')),report=JSON.parse(reportBytes);
  if(hash(manifestBytes)!==provenance.inputManifestSHA256||hash(reportBytes)!==provenance.inputBuildReportSHA256)throw new Error('staging metadata differs from reviewed provenance');
  const counts={sourceFiles:report.sourceFiles.length,routes:report.routes,stagedFiles:report.stagedFiles,stagedBytes:report.stagedBytes,sourceBytes:report.sourceBytes};
  if(!same(counts,provenance.counts)||!Object.values(counts).every(positive)||!same(Object.keys(original).sort(),approvedRoutes))throw new Error('snapshot differs from reviewed release routes/counts');
  const parts=new Map(),routes={};
  for(const [path,entry]of Object.entries(original)){
    if(!positive(entry.size)||!sha(entry.sha256)||!Array.isArray(entry.parts)||!entry.parts.length||typeof entry.contentType!=='string')throw new Error('invalid logical route: '+path);
    const logicalHash=createHash('sha256'),mapped=[];let size=0;
    for(const [index,part]of entry.parts.entries()){
      if(!(runtimeSources.some(s=>s.path===part.path)||part.path==='/__chunks/'+entry.sha256+'/'+index)||
        !positive(part.size)||part.size>20*1024*1024)throw new Error('invalid part');
      const bytes=await readFile(resolve(snapshot,'public','.'+part.path)),sha256=hash(bytes);
      if(bytes.length!==part.size)throw new Error('part size mismatch');
      const pin={source:part.path,path:'/_runtime_assets/'+sha256+'.bin',size:bytes.length,sha256};
      if(parts.has(part.path)&&!same(parts.get(part.path),pin))throw new Error('part changed during pin');
      parts.set(part.path,pin);mapped.push({path:pin.path,size:pin.size});logicalHash.update(bytes);size+=bytes.length;
    }
    if(size!==entry.size||logicalHash.digest('hex')!==entry.sha256)throw new Error('logical hash mismatch: '+path);
    routes[path]={...entry,parts:mapped};
  }
  if(Object.keys(routes).length!==report.routes||parts.size!==report.stagedFiles||
    [...parts.values()].reduce((n,p)=>n+p.size,0)!==report.stagedBytes||report.sourceFiles.reduce((n,s)=>n+s.size,0)!==report.sourceBytes)throw new Error('snapshot counts mismatch');
  if(!same(report.sourceFiles.map(s=>({source:s.source,path:s.path})),runtimeSources))throw new Error('unapproved source allowlist');
  if(!same(provenance.sources.map(s=>({source:s.source,path:s.path})),runtimeSources))throw new Error('unapproved provenance source allowlist');
  for(const source of report.sourceFiles){
    const entry=original[source.path],pin=provenance.sources.find(s=>s.path===source.path);
    if(!entry||entry.size!==source.size||entry.sha256!==source.sha256||entry.parts.length!==source.parts||
      pin.size!==source.size||pin.sha256!==source.sha256)throw new Error('report/provenance/manifest mismatch');
  }
  for(const [alias,path]of Object.entries(runtimeAliases))if(!same(original[alias],original[path]))throw new Error('legacy alias mismatch');
  const boot=JSON.parse(await readFile(resolve(snapshot,'public/linux/boot-manifest.json'),'utf8'));
  if(!same(boot,provenance.bootManifest))throw new Error('boot manifest differs from reviewed release');
  for(const image of Object.values(boot.assets)){
    const entry=original[new URL(image.url,'https://local/linux/boot-manifest.json').pathname];
    if(!entry||entry.sha256!==image.sha256||entry.size!==image.bytes)throw new Error('boot manifest/image mismatch');
  }
  const module='// Pinned runtime routes. Update only with pin-runtime.mjs.\nexport default '+JSON.stringify(routes,null,2)+';\n';
  const lock={schema:1,parentCommit,stagedBytes:report.stagedBytes,stagedFiles:parts.size,routes:report.routes,
    runtimeManifestSHA256:hash(module),inputManifestSHA256:hash(manifestBytes),inputBuildReportSHA256:hash(reportBytes),
    releaseProvenanceSHA256:hash(provenanceBytes),releaseProvenance:provenance,
    parts:[...parts.values()].sort((a,b)=>a.source.localeCompare(b.source))};
  await writeFile(resolve(output,'runtime-assets.mjs'),module);
  await writeFile(resolve(output,'runtime-lock.json'),JSON.stringify(lock,null,2)+'\n');
  return lock;
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url)){
  const lock=await pinRuntime(...process.argv.slice(2));
  console.log(JSON.stringify({parentCommit:lock.parentCommit,routes:lock.routes,parts:lock.stagedFiles,stagedBytes:lock.stagedBytes,runtimeManifestSHA256:lock.runtimeManifestSHA256,releaseProvenanceSHA256:lock.releaseProvenanceSHA256}));
}
