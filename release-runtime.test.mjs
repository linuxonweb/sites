import assert from 'node:assert/strict';
import test from 'node:test';
import { mkdtemp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { approvedRoutes, digest, reviewDependencies, runtimeAliases, runtimeSources } from './release-runtime.mjs';
import { pinRuntime } from './pin-runtime.mjs';

test('current production module and worker URLs have an explicit allowlisted closure',async()=>{
  const root=process.env.SITES_RUNTIME_SOURCE?resolve(process.env.SITES_RUNTIME_SOURCE):resolve(new URL('../..',import.meta.url).pathname);
  const deps=await reviewDependencies(async path=>(await readFile(join(root,'web'+path))).toString('utf8'));
  for(const path of ['/linux/tests/guest-gpu/host.mjs','/linux/tests/guest-vulkan-graphics/translator/worker.mjs',
    '/linux/tests/guest-vulkan-webgl/translator/worker.mjs','/linux/tests/firefox-webgpu-decoder/decoder.mjs',
    '/linux/dist/firefox-webgpu-decoder.wasm'])assert.ok(deps.some(d=>d.path===path),path);
  assert.ok(!approvedRoutes.some(p=>/\.test\.|\/candidate|\.html$/.test(p)&&p.includes('/tests/')));
  const hostSource=async path=>{
    const source=(await readFile(join(root,'web'+path))).toString('utf8');
    return path==='/linux/gputest.mjs'?source+'\nconst allowCompute = true;':source;
  };
  await assert.rejects(reviewDependencies(hostSource),/compute enablement/);
});

async function fixture() {
  const temp=process.env.TMPDIR;
  if(!temp||!resolve(temp).startsWith('/mnt/p6/build/'))throw new Error('Tests require task TMPDIR under /mnt/p6/build');
  const dir=await mkdtemp(join(temp,'sites-pin-')),snapshot=join(dir,'snapshot'),output=join(dir,'pinned');
  await mkdir(join(snapshot,'generated'),{recursive:true});await mkdir(output);
  const data=new Map(runtimeSources.map(s=>[s.path,Buffer.from('fixture:'+s.path)]));
  const boot={schema:1,version:'fixture-release',assets:Object.fromEntries(['kernel','plain','firefox'].map((name,i)=>{
    const path=['/linux/vmlinux.wasm','/linux/initramfs.cpio','/linux/initramfs-firefox.cpio.gz'][i],bytes=data.get(path);
    return [name,{url:'./'+path.split('/').pop(),bytes:bytes.length,sha256:digest(bytes)}];
  }))};
  data.set('/linux/boot-manifest.json',Buffer.from(JSON.stringify(boot)));
  const manifest={},sources=[];
  for(const source of runtimeSources){
    const bytes=data.get(source.path),path=join(snapshot,'public',source.path);await mkdir(dirname(path),{recursive:true});await writeFile(path,bytes);
    manifest[source.path]={size:bytes.length,sha256:digest(bytes),contentType:'application/octet-stream',parts:[{path:source.path,size:bytes.length}]};
    sources.push({...source,size:bytes.length,sha256:digest(bytes)});
  }
  for(const [alias,path]of Object.entries(runtimeAliases))manifest[alias]=manifest[path];
  const sourceBytes=sources.reduce((n,s)=>n+s.size,0);
  const report={sourceFiles:sources.map(s=>({...s,parts:1})),routes:approvedRoutes.length,sourceBytes,stagedFiles:sources.length,stagedBytes:sourceBytes};
  const parentCommit='a'.repeat(40),provenance={schema:1,parentCommit,auditSHA256:'b'.repeat(64),helperSHA256:digest(await readFile(new URL('./release-runtime.mjs',import.meta.url))),
    approvedRoutes,aliases:runtimeAliases,bootManifest:boot,sources,
    counts:{sourceFiles:sources.length,routes:report.routes,stagedFiles:report.stagedFiles,stagedBytes:report.stagedBytes,sourceBytes}};
  async function save(){
    const manifestBytes='// Generated by stage-assets.mjs. Do not edit.\nexport default '+JSON.stringify(manifest)+';\n',reportBytes=JSON.stringify(report);
    provenance.inputManifestSHA256=digest(manifestBytes);provenance.inputBuildReportSHA256=digest(reportBytes);
    await writeFile(join(snapshot,'generated/asset-manifest.mjs'),manifestBytes);await writeFile(join(snapshot,'generated/build-report.json'),reportBytes);
    await writeFile(join(snapshot,'generated/release-provenance.json'),JSON.stringify(provenance));
  }
  const pin=()=>pinRuntime(snapshot,parentCommit,join(snapshot,'generated/release-provenance.json'),output);
  await save();return {dir,manifest,report,provenance,output,save,pin,snapshot};
}
test('new release counts are audited and pinning rejects route, part, image and provenance tampering',async()=>{
  const f=await fixture();
  try{
    const lock=await f.pin();assert.equal(lock.routes,approvedRoutes.length);assert.equal(lock.stagedFiles,runtimeSources.length);
    assert.equal(lock.releaseProvenance.bootManifest.version,'fixture-release');
    f.provenance.counts.stagedBytes++;await f.save();await assert.rejects(f.pin(),/counts/);f.provenance.counts.stagedBytes--;
    f.manifest['/linux/tests/unapproved.html']=f.manifest['/linux/main.js'];await f.save();await assert.rejects(f.pin(),/routes\/counts/);delete f.manifest['/linux/tests/unapproved.html'];
    const part=f.manifest['/linux/main.js'].parts[0],original=part.path;part.path='/linux/../../private';await f.save();await assert.rejects(f.pin(),/invalid part/);part.path=original;
    const image=f.provenance.bootManifest.assets.firefox,originalHash=image.sha256;image.sha256='d'.repeat(64);await f.save();await assert.rejects(f.pin(),/boot manifest/);image.sha256=originalHash;
    await f.save();await writeFile(join(f.snapshot,'public/linux/main.js'),'changed');await assert.rejects(f.pin(),/part size mismatch|logical hash mismatch/);
  }finally{await rm(f.dir,{recursive:true,force:true});}
});
